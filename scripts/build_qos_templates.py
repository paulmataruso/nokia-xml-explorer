#!/usr/bin/env python3
"""
Builds backend/app/actions/qos_templates.py: the QoS action's built-in
templates, one per 5QI (SA) and per QCI (EN-DC) that production gNBs map.

Production gNBs are the ones whose 5QI mappings name slices (the lab's name
none). For each value the template is the bearer most of them use, with its
MAC, PDCP, RLC and DRX profiles, as values only: no distName, slice or PLMN
leaves the source files. Where a gNB maps one value twice (for different
slices), the mapping whose instance id is the value comes first, and the
other bearers that two or more production gNBs use for the value are kept
as its `variants`.

Usage: python3 scripts/build_qos_templates.py [folder ...]   (default: scp/)
Run from the repo root.
"""
import collections
import os
import pprint
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "backend"))

from app.ca import _load  # noqa: E402
from app.actions.qos_files import summary  # noqa: E402
from app.parser import XmlParseError  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), "..", "backend", "app", "actions", "qos_templates.py")

HEADER = '''"""
Built-in QoS templates (generated by scripts/build_qos_templates.py; don't
edit by hand). One per value: the bearer and profiles that most production
gNBs use for it, as values only. `gnbs` is how many of the `of` production
gNBs in the files this was built from use exactly this template.
"""

TEMPLATES = '''


def main(folders):
    seen, gnbs = set(), 0
    counts = collections.defaultdict(collections.Counter)
    content = {}
    for d in folders:
        for f in sorted(os.listdir(d)):
            if not f.lower().endswith(".xml"):
                continue
            try:
                s = summary(_load(open(os.path.join(d, f), "rb").read()))
            except XmlParseError:
                continue
            for g in s["gnbs"]:
                if not any(p["slices"] for p in g["profiles"]):
                    continue
                key = (g["dn"], tuple(sorted(p["sig"] for p in g["profiles"])))
                if key in seen:
                    continue
                seen.add(key)
                gnbs += 1
                for p in sorted(g["profiles"], key=lambda p: p["dn"].rsplit("-", 1)[-1] not in p["values"]):
                    if not p["bearer"]:
                        continue
                    for v in p["values"]:
                        counts[(p["kind"], v)][p["sig"]] += 1
                        content.setdefault(p["sig"], {"p": p["p"], "bearer": p["bearer"]})
    out = {"5qi": {}, "qci": {}}
    for (kind, v), sigs in sorted(counts.items(), key=lambda kv: (kv[0][0], int(kv[0][1]))):
        (sig, n), *rest = sigs.most_common()
        out[kind][v] = {**content[sig], "gnbs": n, "of": gnbs,
                        "variants": [{**content[x], "gnbs": m, "of": gnbs} for x, m in rest if m >= 2]}
    with open(OUT, "w") as fh:
        fh.write(HEADER + pprint.pformat(out, width=118, sort_dicts=True) + "\n")
    variants = [f"{k} {v}" for k in out for v, t in out[k].items() if t["variants"]]
    print(f"{gnbs} production gNBs; 5QI {', '.join(out['5qi'])}; QCI {', '.join(out['qci'])}; more than one bearer for "
          f"{', '.join(variants) or 'none'} -> {OUT}")


if __name__ == "__main__":
    main(sys.argv[1:] or ["scp"])
