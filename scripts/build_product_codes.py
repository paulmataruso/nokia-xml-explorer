#!/usr/bin/env python3
"""
Builds backend/app/data/product_codes.json, the Nokia hardware catalog
behind the "Change a product code" action: base code (474020A, without
the .102 revision) -> name, kind, family, technology, duplex, bands,
description and the public web pages that pair the code with the name.

Input: research/input/web_product_codes.json, a list of entries collected
from public reseller catalogues, datasheets and Nokia hardware roadmaps
(2026-11-03). Every entry has at least one source URL where the code and
the name appear together. The BTS's own runtime names (productName on the
*_R objects) aren't copied in: the app reads those from the files at run
time and prefers them.

Kinds: radio, mmimo-radio, small-cell, baseband, system-module, sfp,
power, cable, gnss, subrack, alarm, antenna, other ("other" is unclassified:
mounts, cabinets, sub-modules, and 08xxxxA codes that may be core boards).

Also writes docs/product_codes.md, the same catalog as a readable list
with every source link.

Run after changing the input. No other step depends on it.
"""
import json
import re
from collections import Counter
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parent.parent
IN_PATH = ROOT / "research" / "input" / "web_product_codes.json"
OUT_PATH = ROOT / "backend" / "app" / "data" / "product_codes.json"
MD_PATH = ROOT / "docs" / "product_codes.md"

CODE = re.compile(r"^\d{6}[A-Z]$")

# Left out on purpose: the pairing was seen only in a search summary of a
# document that couldn't be opened.
EXCLUDE = {"475169A"}

FIELDS = ("name", "kind", "family", "tech", "duplex", "bands", "description", "sources", "note")

ABOUT = ("Nokia hardware product codes from public web sources (reseller catalogues, datasheets, "
         "Nokia hardware roadmaps), collected 2026-11-03. Each entry lists the pages that pair the "
         "code with the name. Not an official Nokia list.")

# Sections of the readable list, in order.
KINDS = [
    ("radio", "Radios"),
    ("mmimo-radio", "Massive-MIMO radios"),
    ("small-cell", "Small cells"),
    ("baseband", "Baseband cards"),
    ("system-module", "System modules"),
    ("sfp", "SFP transceivers"),
    ("power", "Power"),
    ("cable", "Cables"),
    ("gnss", "GNSS"),
    ("subrack", "Subracks"),
    ("alarm", "Alarm modules"),
    ("antenna", "Antennas"),
    ("other", "Other (unclassified)"),
]

MD_INTRO = """\
# Nokia hardware product codes

{about}

The tool's "Change a product code" action uses this list
(`backend/app/data/product_codes.json`) for its suggestions and to refuse a code of the wrong kind
of module. Where a file's runtime objects (`*_R`) report a name for a code, the app uses that name
instead. This page and the JSON are both generated by `scripts/build_product_codes.py`; don't edit
them by hand.

- **Codes** are base codes, such as 474020A. Files often add a revision (474020A.102).
- **Sources** are the pages where the code and the name appear together. {single} entries rest on a
  single website, so treat them as less certain. The notes say where sources disagree.
- **Left out:** AWEUD 475169A. It was seen only in a search summary of an FCC exhibit that couldn't be
  opened.
- **Not found anywhere:** core-board codes such as 089140A and 088925A. The BTS reports them as
  `coreHwBoardProductCode`; they are not module codes.
- **"Other"** is unclassified: mounts, cabinets, sub-modules, and 08xxxxA codes that may be core or
  board codes rather than sales items.

| Kind | Codes |
|---|---:|
{counts}
"""


def main():
    rows = json.loads(IN_PATH.read_text())
    codes: dict = {}
    for r in rows:
        code = r["code"].strip()
        if code in EXCLUDE or not CODE.match(code):
            continue
        entry = {k: r[k] for k in FIELDS if r.get(k) not in (None, "", [])}
        # One name per code: the one more sources agree on (473262A is
        # FZHN in the Nokia roadmap; one listing transposes it to FHZN).
        old = codes.get(code)
        if old is None or len(entry.get("sources", [])) > len(old.get("sources", [])):
            codes[code] = entry
    OUT_PATH.write_text(json.dumps({
        "about": ABOUT,
        "codes": codes,
    }, indent=1, sort_keys=True) + "\n")
    kinds = Counter(e.get("kind", "other") for e in codes.values())
    MD_PATH.parent.mkdir(exist_ok=True)
    MD_PATH.write_text(markdown(codes, kinds))
    print(f"{len(codes)} codes -> {OUT_PATH.relative_to(ROOT)}, {MD_PATH.relative_to(ROOT)}: "
          + ", ".join(f"{k} {n}" for k, n in sorted(kinds.items())))


def _cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def _site(url: str) -> str:
    host = urlparse(url).netloc
    return host[4:] if host.startswith("www.") else host


def markdown(codes: dict, kinds: Counter) -> str:
    titles = dict(KINDS)
    out = [MD_INTRO.format(
        about=ABOUT,
        single=sum(1 for e in codes.values() if len({_site(u) for u in e.get("sources", [])}) == 1),
        counts="\n".join(f"| [{titles[k]}](#{titles[k].lower().replace(' ', '-').replace('(', '').replace(')', '')}) "
                         f"| {kinds[k]} |" for k, _ in KINDS if kinds[k]),
    )]
    for kind, title in KINDS:
        rows = sorted(((c, e) for c, e in codes.items() if e.get("kind", "other") == kind),
                      key=lambda ce: (ce[1].get("name") or "", ce[0]))
        if not rows:
            continue
        out.append(f"\n## {title}\n\n| Code | Name | Family | Tech | Bands | Description | Sources |\n"
                   "|---|---|---|---|---|---|---|")
        for code, e in rows:
            tech = " ".join(x for x in (e.get("tech"), e.get("duplex")) if x)
            desc = _cell(e.get("description", ""))
            if e.get("note"):
                desc += f" *Note: {_cell(e['note'])}*"
            links = ", ".join(f"[{_site(u)}]({u})" for u in e.get("sources", []))
            out.append(f"| {code} | {_cell(e.get('name', ''))} | {_cell(e.get('family', ''))} | {tech} | "
                       f"{', '.join(e.get('bands', []))} | {desc} | {links} |")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    main()
